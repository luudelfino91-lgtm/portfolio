CREATE TABLE centros_distribuicao (
  id INTEGER PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE,
  cidade TEXT NOT NULL,
  capacidade_diaria INTEGER NOT NULL
);
CREATE TABLE transportadoras (
  id INTEGER PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE,
  email_contato TEXT,
  ativa INTEGER NOT NULL CHECK (ativa IN (0, 1))
);
CREATE TABLE veiculos (
  id INTEGER PRIMARY KEY,
  transportadora_id INTEGER NOT NULL REFERENCES transportadoras (id),
  codigo TEXT NOT NULL UNIQUE,
  tipo TEXT NOT NULL,
  capacidade_kg INTEGER NOT NULL
);
CREATE TABLE rotas (
  id INTEGER PRIMARY KEY,
  centro_id INTEGER NOT NULL REFERENCES centros_distribuicao (id),
  destino TEXT NOT NULL,
  distancia_km REAL NOT NULL
);
CREATE TABLE entregas (
  id INTEGER PRIMARY KEY,
  rota_id INTEGER NOT NULL REFERENCES rotas (id),
  veiculo_id INTEGER NOT NULL REFERENCES veiculos (id),
  data_prevista TEXT NOT NULL,
  data_realizada TEXT,
  status TEXT NOT NULL CHECK (status IN ('entregue', 'em_transito', 'devolvida', 'cancelada')),
  atraso_dias INTEGER,
  peso_kg REAL NOT NULL,
  custo REAL NOT NULL
);
CREATE TABLE ocorrencias (
  id INTEGER PRIMARY KEY,
  entrega_id INTEGER NOT NULL REFERENCES entregas (id),
  tipo TEXT NOT NULL,
  data_ocorrencia TEXT NOT NULL,
  descricao TEXT
);

