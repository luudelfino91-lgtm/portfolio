CREATE TABLE canais (
  id INTEGER PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE,
  tipo TEXT NOT NULL CHECK (tipo IN ('pago', 'proprio', 'parceiro'))
);
CREATE TABLE campanhas (
  id INTEGER PRIMARY KEY,
  nome TEXT NOT NULL,
  objetivo TEXT NOT NULL,
  data_inicio TEXT NOT NULL,
  data_fim TEXT,
  orcamento REAL NOT NULL
);
CREATE TABLE anuncios (
  id INTEGER PRIMARY KEY,
  campanha_id INTEGER NOT NULL REFERENCES campanhas (id),
  canal_id INTEGER NOT NULL REFERENCES canais (id),
  nome TEXT NOT NULL,
  formato TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('ativo', 'pausado', 'encerrado'))
);
CREATE TABLE metricas_diarias (
  id INTEGER PRIMARY KEY,
  anuncio_id INTEGER NOT NULL REFERENCES anuncios (id),
  data TEXT NOT NULL,
  impressoes INTEGER NOT NULL,
  cliques INTEGER NOT NULL CHECK (cliques <= impressoes),
  custo REAL NOT NULL,
  conversoes INTEGER NOT NULL CHECK (conversoes <= cliques),
  receita REAL NOT NULL,
  UNIQUE (anuncio_id, data)
);
CREATE TABLE leads (
  id INTEGER PRIMARY KEY,
  campanha_id INTEGER NOT NULL REFERENCES campanhas (id),
  canal_id INTEGER NOT NULL REFERENCES canais (id),
  nome TEXT NOT NULL,
  email TEXT,
  criado_em TEXT NOT NULL,
  convertido_em TEXT,
  valor_contrato REAL
);

