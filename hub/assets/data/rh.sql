CREATE TABLE departamentos (
  id INTEGER PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE,
  centro_custo TEXT NOT NULL
);
CREATE TABLE cargos (
  id INTEGER PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE,
  departamento_id INTEGER NOT NULL REFERENCES departamentos (id),
  nivel INTEGER NOT NULL CHECK (nivel BETWEEN 1 AND 5)
);
CREATE TABLE funcionarios (
  id INTEGER PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL,
  cargo_id INTEGER NOT NULL REFERENCES cargos (id),
  departamento_id INTEGER NOT NULL REFERENCES departamentos (id),
  gestor_id INTEGER REFERENCES funcionarios (id),
  data_admissao TEXT NOT NULL,
  data_desligamento TEXT
);
CREATE TABLE salarios_historico (
  id INTEGER PRIMARY KEY,
  funcionario_id INTEGER NOT NULL REFERENCES funcionarios (id),
  data_inicio TEXT NOT NULL,
  salario REAL NOT NULL,
  motivo TEXT NOT NULL CHECK (motivo IN ('admissao', 'reajuste')),
  UNIQUE (funcionario_id, data_inicio)
);
CREATE TABLE avaliacoes (
  id INTEGER PRIMARY KEY,
  funcionario_id INTEGER NOT NULL REFERENCES funcionarios (id),
  avaliador_id INTEGER NOT NULL REFERENCES funcionarios (id),
  periodo TEXT NOT NULL,
  nota INTEGER CHECK (nota BETWEEN 1 AND 5),
  comentario TEXT,
  UNIQUE (funcionario_id, periodo)
);
CREATE TABLE ausencias (
  id INTEGER PRIMARY KEY,
  funcionario_id INTEGER NOT NULL REFERENCES funcionarios (id),
  tipo TEXT NOT NULL CHECK (tipo IN ('ferias', 'atestado', 'licenca')),
  data_inicio TEXT NOT NULL,
  data_fim TEXT NOT NULL,
  dias INTEGER NOT NULL CHECK (dias > 0)
);

