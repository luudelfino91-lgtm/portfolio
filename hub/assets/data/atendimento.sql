CREATE TABLE clientes (
  id INTEGER PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT,
  plano TEXT NOT NULL CHECK (plano IN ('basico', 'pro', 'empresarial')),
  data_cadastro TEXT NOT NULL
);
CREATE TABLE agentes (
  id INTEGER PRIMARY KEY,
  nome TEXT NOT NULL,
  equipe TEXT NOT NULL,
  data_entrada TEXT NOT NULL
);
CREATE TABLE tickets (
  id INTEGER PRIMARY KEY,
  cliente_id INTEGER NOT NULL REFERENCES clientes (id),
  agente_id INTEGER REFERENCES agentes (id),
  assunto TEXT NOT NULL,
  prioridade TEXT NOT NULL CHECK (prioridade IN ('baixa', 'media', 'alta', 'urgente')),
  canal TEXT NOT NULL CHECK (canal IN ('email', 'chat', 'telefone', 'formulario')),
  status TEXT NOT NULL CHECK (status IN ('aberto', 'em_andamento', 'resolvido', 'fechado')),
  aberto_em TEXT NOT NULL,
  fechado_em TEXT
);
CREATE TABLE interacoes (
  id INTEGER PRIMARY KEY,
  ticket_id INTEGER NOT NULL REFERENCES tickets (id),
  autor_tipo TEXT NOT NULL CHECK (autor_tipo IN ('cliente', 'agente')),
  agente_id INTEGER REFERENCES agentes (id),
  data_hora TEXT NOT NULL,
  mensagem TEXT NOT NULL
);
CREATE TABLE pesquisas_satisfacao (
  id INTEGER PRIMARY KEY,
  ticket_id INTEGER NOT NULL UNIQUE REFERENCES tickets (id),
  nota INTEGER CHECK (nota BETWEEN 1 AND 5),
  comentario TEXT,
  respondida_em TEXT
);

